/** Additif reçu soit en string legacy ("E150d") soit en objet depuis /api/scan. */
export type AdditiveRef = string | { code: string; name?: string; risk?: "high" | "moderate" | "low" | "unknown" | null }

/** AL-08 / EB-04 — Scanned product from barcode. */
export interface ScannedProduct {
  id?: number       // présent via GET /api/scanned (absent après POST /api/scan)
  barcode: string
  name: string
  nutriScore: "A" | "B" | "C" | "D" | "E" | null
  /** 0–100 (AL-08). null = « non noté » (P1-7) — aucune donnée exploitable, NE PAS colorer comme un mauvais score. */
  score: number | null
  /** null = « non noté » (P1-7). */
  verdict: "Excellent" | "Médiocre" | "Mauvais" | null
  /** Source du score (P1-7) : OFF, recalculé officiel, ou non noté. */
  nutriScoreSource?: "nutriscore_off" | "nutriscore_calcule" | "non_note"
  additives: AdditiveRef[]
  timesThisMonth: number
  sucres?: number  // g per 100g
  sel?: number     // g per 100g
  ags?: number     // g per 100g (acides gras saturés)
  scannedAt?: string // ISO timestamp (GET /api/scanned)
  imageUrl?: string | null  // S10c — photo du produit OFF
}

/** S12 — Alternative plus saine proposée pour un produit scanné (live OpenFoodFacts). */
export interface Alternative {
  barcode: string
  name: string
  nutriScore: "A" | "B" | "C" | "D" | "E" | null
  imageUrl: string | null
}

